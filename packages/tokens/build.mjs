/**
 * @epharmatica/tokens build — Style Dictionary pipeline (STYLE.md §16, S11).
 *
 * tokens/*.json is the single source of truth. This script emits:
 *   dist/tokens.css     — Tailwind v4 @theme block (light) + .dark overrides
 *   src/generated.ts    — typed TS constants (light + dark), consumed via src/index.ts
 *   dist/figma.tokens.json — Tokens-Studio import file for Figma
 *
 * Tokens are edited ONLY in the JSON files. Raw hexes exist once, here.
 */
import StyleDictionary from 'style-dictionary'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))

const cssVarName = (token) => {
  // color.ink-2 -> --color-ink-2 · radius.default -> --radius · z.sticky -> --z-sticky
  const path = [...token.path]
  if (path[0] === 'radius' && path[1] === 'default') return '--radius'
  return `--${path.join('-')}`
}

async function flatten(files) {
  const sd = new StyleDictionary({
    source: files.map((f) => join(root, 'tokens', f)),
    platforms: { js: { transformGroup: 'js' } },
  })
  const dict = await sd.getPlatformTokens('js')
  return dict.allTokens
}

const [light, dark] = await Promise.all([
  flatten(['base.json', 'theme-light.json']),
  flatten(['theme-dark.json']),
])

// --- dist/tokens.css -------------------------------------------------------
const themeLines = light.map((t) => `  ${cssVarName(t)}: ${t.value};`).join('\n')
const darkLines = dark.map((t) => `  ${cssVarName(t)}: ${t.value};`).join('\n')

const css = `/* GENERATED by @epharmatica/tokens — do not edit. Source: tokens/*.json */
/* Pharmacopoeia · STYLE.md v1.3 (locked) · radius 0px is founder-final (S1) */

@theme {
${themeLines}
}

/* Dark theme — first-class, toggled via .dark on <html> (next-themes) */
.dark {
${darkLines}
}
`

// --- src/generated.ts ------------------------------------------------------
const toObject = (tokens) => {
  const out = {}
  for (const t of tokens) {
    let node = out
    for (const p of t.path.slice(0, -1)) node = node[p] ??= {}
    node[t.path.at(-1)] = t.value
  }
  return out
}
const ts = `/* GENERATED by @epharmatica/tokens — do not edit. Source: tokens/*.json */
export const tokens = ${JSON.stringify(toObject(light), null, 2)} as const

export const darkTokens = ${JSON.stringify(toObject(dark), null, 2)} as const

export type Tokens = typeof tokens
`

// --- dist/figma.tokens.json (Tokens Studio) --------------------------------
const readJson = async (f) => JSON.parse(await readFile(join(root, 'tokens', f), 'utf8'))
const figma = {
  global: await readJson('base.json'),
  light: await readJson('theme-light.json'),
  dark: await readJson('theme-dark.json'),
}

await mkdir(join(root, 'dist'), { recursive: true })
await writeFile(join(root, 'dist', 'tokens.css'), css)
await writeFile(join(root, 'src', 'generated.ts'), ts)
await writeFile(join(root, 'dist', 'figma.tokens.json'), JSON.stringify(figma, null, 2))

console.log(
  `@epharmatica/tokens: ${light.length} tokens → dist/tokens.css, src/generated.ts, dist/figma.tokens.json`,
)
